def render_html(conn: sqlite3.Connection, case_id: int, redact: bool = True) -> str | None:
    data = _gather(conn, case_id)
    if data is None:
        return None
    R = build_redactor(conn, case_id).scrub if redact else (lambda s: s or "")
    def E(s):  # redact then HTML-escape
        return html.escape(R(s))
    c, b = data["case"], data["bundle"]
    counts = ", ".join(f"{s['source']}={s['n']}" for s in data["by_source"]) or "none parsed"
    parts = [f"<!doctype html><html><head><meta charset='utf-8'>",
             f"<title>RCA Case {case_id}</title><style>{_HTML_CSS}</style></head><body>",
             f"<h1>RCA Report — Case {case_id}</h1>",
             "<div class='meta'>",
             f"<div><b>Symptom:</b> {E(c['symptom_text'])}</div>"]
    if b:
        parts.append(f"<div><b>Machine:</b> {E(b['machine_name']) or '?'} &middot; "
                     f"<b>Collected:</b> {html.escape(b['collected_utc'] or '?')} &middot; "
                     f"<b>Device TZ:</b> {data['tz']}</div>")
    parts.append(f"<div><b>Events:</b> {html.escape(counts)}</div>")
    parts.append(f"<div><b>Generated:</b> {now_utc_iso()} &middot; "
                 f"{'redacted' if redact else '<b>NOT redacted</b>'}</div></div>")
    parts.append("<h2>Findings</h2>")
    if not data["findings"]:
        parts.append("<p><em>No findings — run analyze.</em></p>")
    for f in data["findings"]:
        sev = html.escape(f["severity"])
        parts.append(f"<div class='f'><h3><span class='badge {sev}'>{sev}</span> "
                     f"{E(f['title'])} <small>({html.escape(f['confidence'])} confidence)</small></h3>")
        parts.append(f"<p>{E(f['summary'])}</p>")
        parts.append(f"<div class='fix'><b>Fix:</b> {E(f['recommendation'])}</div>")
        ev = data["evidence"].get(f["id"], [])
        if ev:
            parts.append("<ul class='ev'>")
            for e in ev:
                ts = html.escape(e["ts_local"] or e["ts_utc"] or "?")
                parts.append(f"<li><span class='mono'>{ts}</span> {html.escape(e['source'])} "
                             f"<span class='mono'>{html.escape(e['event_code'] or '')}</span> — "
                             f"{E(e['message'])[:200]}</li>")
            parts.append("</ul>")
        parts.append("</div>")
    parts.append("<p class='foot'>Generated by Intune RCA.</p></body></html>")
    return "".join(parts)
