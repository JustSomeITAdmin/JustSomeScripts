"""Shareable RCA report for a case — Markdown or standalone HTML.

Both formats are built from the same data and run every shared string through a
redactor (default on) so the output is safe to attach to a ticket or hand to a
colleague. HTML is self-contained (inline CSS, no assets) for easy handoff.
"""

from __future__ import annotations

import html
import sqlite3

from rca.models import SEVERITY_RANK
from rca.redact import build_redactor
from rca.ruleset import CONFIDENCE_RANK
from rca.timeutil import format_offset
from rca.util import now_utc_iso


def _gather(conn: sqlite3.Connection, case_id: int) -> dict | None:
    case = conn.execute("SELECT * FROM cases WHERE id = ?", (case_id,)).fetchone()
    if case is None:
        return None
    bundle = conn.execute(
        "SELECT * FROM bundles WHERE case_id = ? ORDER BY id LIMIT 1", (case_id,)).fetchone()
    by_source = conn.execute(
        "SELECT source, COUNT(*) n FROM events WHERE case_id = ? GROUP BY source ORDER BY n DESC",
        (case_id,)).fetchall()
    findings = conn.execute(
        """SELECT f.id, f.severity, f.confidence, f.title, f.summary, f.recommendation
           FROM findings f WHERE f.case_id = ? """, (case_id,)).fetchall()
    findings = sorted(findings, key=lambda r: (SEVERITY_RANK.get(r["severity"], 0),
                                               CONFIDENCE_RANK.get(r["confidence"], 0)), reverse=True)
    evidence = {}
    for f in findings:
        evidence[f["id"]] = conn.execute(
            """SELECT e.ts_local, e.ts_utc, e.source, e.event_code, e.message
               FROM finding_evidence fe JOIN events e ON e.id = fe.event_id
               WHERE fe.finding_id = ? ORDER BY e.ts_utc LIMIT 5""", (f["id"],)).fetchall()
    tz = format_offset(bundle["tz_offset_minutes"]) if bundle else "UTC?"
    return {"case": case, "bundle": bundle, "by_source": by_source,
            "findings": findings, "evidence": evidence, "tz": tz}


def render_markdown(conn: sqlite3.Connection, case_id: int, redact: bool = True) -> str | None:
    data = _gather(conn, case_id)
    if data is None:
        return None
    R = build_redactor(conn, case_id).scrub if redact else (lambda s: s or "")
    c, b = data["case"], data["bundle"]
    L: list[str] = [f"# RCA Report — Case {case_id}", ""]
    L.append(f"**Symptom:** {R(c['symptom_text'])}")
    if b:
        L.append(f"**Machine:** {R(b['machine_name']) or '?'} · **Collected:** "
                 f"{b['collected_utc'] or '?'} · **Device TZ:** {data['tz']}")
    counts = ", ".join(f"{s['source']}={s['n']}" for s in data["by_source"]) or "none parsed"
    L.append(f"**Events:** {counts}")
    L.append(f"**Generated:** {now_utc_iso()}{'  ·  redacted' if redact else '  ·  NOT redacted'}")
    L += ["", "## Findings", ""]
    if not data["findings"]:
        L.append("_No findings — run analyze._")
    for f in data["findings"]:
        L.append(f"### [{f['severity']}/{f['confidence']}] {R(f['title'])}")
        L.append(R(f["summary"]) or "")
        L.append(f"**Fix:** {R(f['recommendation'])}")
        ev = data["evidence"].get(f["id"], [])
        if ev:
            L.append("")
            L.append("Evidence:")
            for e in ev:
                ts = e["ts_local"] or e["ts_utc"] or "?"
                L.append(f"- `{ts}` {e['source']} {e['event_code'] or ''} — "
                         f"{R(e['message'])[:200]}")
        L.append("")
    L.append("---")
    L.append("_Generated by Intune RCA._")
    return "\n".join(L)


